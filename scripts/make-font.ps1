# Rasterizes the theme fonts (8-bit coverage per pixel).
# font.h: Zoid: Bahnschrift Bold. Cyberpunk: Bahnschrift SemiBold Condensed. Phosphor: Lucida Console.
# font_paper.h (-Only paper -OutFile font_paper.h): Books' Manga Paper look, Cambria like desktop Paper.
# Each theme has small/medium/large (ASCII 32-126) and a clock size ('+' to ':' only).
param([string[]]$Only = @('zoid','cyber','ph'), [string]$OutFile = 'font.h')
Add-Type -AssemblyName System.Drawing
$out = [System.Text.StringBuilder]::new()
[void]$out.AppendLine('/* Rasterized theme fonts, generated by make-font.ps1. */')
$themes = @(
    @{n='zoid';  f='Bahnschrift';                    s=[System.Drawing.FontStyle]::Bold;    sizes=@(11,15,18,26)},
    @{n='cyber'; f='Bahnschrift SemiBold Condensed'; s=[System.Drawing.FontStyle]::Regular; sizes=@(13,17,20,30)},
    @{n='ph';    f='Lucida Console';                 s=[System.Drawing.FontStyle]::Regular; sizes=@(11,14,16,24)},
    @{n='paper'; f='Cambria';                        s=[System.Drawing.FontStyle]::Regular; sizes=@(13,16,22,26)},
    # font_ms.h (-Only ms1,ms2,msp -OutFile font_ms.h): the Zoidstation skins (zoidstation.h)
    @{n='ms1';   f='Arial Rounded MT Bold';          s=[System.Drawing.FontStyle]::Regular; sizes=@(11,14,18,26)},
    @{n='ms2';   f='Century Gothic';                 s=[System.Drawing.FontStyle]::Regular; sizes=@(12,15,19,28)},
    @{n='msp';   f='Segoe UI';                       s=[System.Drawing.FontStyle]::Regular; sizes=@(12,15,19,28)}
) | Where-Object { $Only -contains $_.n }
$cells = @(@('small',20,18,32,126),@('medium',24,22,32,126),@('large',28,30,32,126),@('clock',24,44,43,58))
foreach ($t in $themes) {
  for ($i=0; $i -lt 4; $i++) {
    $name=$cells[$i][0]; $w=$cells[$i][1]; $h=$cells[$i][2]; $first=$cells[$i][3]; $last=$cells[$i][4]
    $count=$last-$first+1
    $font=[System.Drawing.Font]::new($t.f,$t.sizes[$i],$t.s,[System.Drawing.GraphicsUnit]::Pixel)
    $bmp=[System.Drawing.Bitmap]::new($w,$h)
    $g=[System.Drawing.Graphics]::FromImage($bmp)
    $g.TextRenderingHint=[System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
    $fmt=[System.Drawing.StringFormat]::GenericTypographic.Clone()
    $fmt.FormatFlags=$fmt.FormatFlags -bor [System.Drawing.StringFormatFlags]::MeasureTrailingSpaces
    # the clock font is shifted up so digits sit inside the cell
    $dy = if ($name -eq 'clock') { -[Math]::Round($t.sizes[$i]*0.08) } else { 0 }
    $widths=[System.Collections.Generic.List[int]]::new()
    $label="font_$($t.n)_$name"
    [void]$out.AppendLine("static const unsigned char ${label}[$count][$($w*$h)] = {")
    foreach ($code in $first..$last) {
        $g.Clear([System.Drawing.Color]::Black)
        $str=[string][char]$code
        $width=[Math]::Min($w,[Math]::Ceiling($g.MeasureString($str,$font,200,$fmt).Width))
        $widths.Add([Math]::Max(3,$width))
        $g.DrawString($str,$font,[System.Drawing.Brushes]::White,0,$dy,$fmt)
        $values=[byte[]]::new($w*$h)
        for($y=0;$y -lt $h;$y++){for($x=0;$x -lt $w;$x++){$values[$y*$w+$x]=$bmp.GetPixel($x,$y).R}}
        [void]$out.AppendLine('{'+($values -join ',')+'},')
    }
    [void]$out.AppendLine('};')
    [void]$out.AppendLine("static const unsigned char widths_$($t.n)_${name}[$count] = {"+($widths -join ',')+'};')
    $g.Dispose();$bmp.Dispose();$font.Dispose();$fmt.Dispose()
  }
}
[System.IO.File]::WriteAllText((Join-Path (Join-Path $PSScriptRoot '..\src\fonts') $OutFile),$out.ToString())
